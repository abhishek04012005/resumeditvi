const toTitleCase = (value: string): string => {
    const smallWords = new Set([
        "a",
        "an",
        "the",
        "and",
        "or",
        "for",
        "of",
        "in",
        "on",
        "with",
        "to",
        "at",
        "by",
        "from",
        "as",
    ]);

    return value
        .toLowerCase()
        .split(/\s+/)
        .filter(Boolean)
        .map((word, index) => {
            if (index > 0 && smallWords.has(word)) {
                return word;
            }
            return word.charAt(0).toUpperCase() + word.slice(1);
        })
        .join(" ");
};

